const CREATE_ACTIVITES = `
  CREATE TABLE IF NOT EXISTS activites (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_activite text    NOT NULL,
    slug         text    NOT NULL UNIQUE,
    categorie    text    NOT NULL CHECK (categorie IN (${inArray(CATEGORIES)})),
    description  text    NOT NULL,
    jour         text    NOT NULL CHECK (jour IN (${inArray(DAYS)})),
    horaire      text    NOT NULL,
    tarif        numeric(6,2) NOT NULL CHECK (tarif >= 0 AND tarif <= 1000),
    places       integer NOT NULL CHECK (places >= 1 AND places <= 200),
    created_at   timestamptz NOT NULL DEFAULT now()
  )
`;

const CREATE_ALIASES = `
  CREATE TABLE IF NOT EXISTS activite_aliases (
    alias       text    PRIMARY KEY,
    activite_id integer NOT NULL REFERENCES activites(id) ON DELETE CASCADE
  )
`;

const CREATE_ADHERENTS = `
  CREATE TABLE IF NOT EXISTS adherents (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prenom         text    NOT NULL,
    nom            text    NOT NULL,
    email          text    NOT NULL UNIQUE,
    telephone      text    NOT NULL,
    date_naissance text    NOT NULL,
    adresse        text    NOT NULL,
    activite_id    integer REFERENCES activites(id) ON DELETE SET NULL,
    statut         text    NOT NULL DEFAULT 'en_attente'
                   CHECK (statut IN (${inArray(STATUSES)})),
    created_at     timestamptz NOT NULL DEFAULT now()
  )
`;

const CREATE_INDEXES = `
  CREATE INDEX IF NOT EXISTS idx_adherents_activite ON adherents(activite_id);
  CREATE INDEX IF NOT EXISTS idx_activites_slug       ON activites(slug);
`;

const tableExists = async (client, name) => {
  const { rows } = await client.query('SELECT to_regclass($1) IS NOT NULL AS present', [name]);
  return rows[0].present;
};

const columnsOf = async (client, name) => {
  if (!(await tableExists(client, name))) return [];
  const { rows } = await client.query(
    'SELECT column_name FROM information_schema.columns WHERE table_name = $1',
    [name]
  );
  return rows.map((r) => r.column_name);
};

async function seedActivities(client) {
  const { rows } = await client.query('SELECT count(*)::int AS n FROM activites');
  if (rows[0].n > 0) return;

  for (const a of SEED_ACTIVITIES) {
    await client.query(
      `INSERT INTO activites (nom_activite, slug, categorie, description, jour, horaire, tarif, places)
       VALUES ($1,$2,$3,$4,$5,$6,$7,$8)`,
      [a.nom_activite, toSlug(a.nom_activite), a.categorie, a.description, a.jour, a.horaire, a.tarif, a.places]
    );
  }
}

async function seedAliases(client) {
  for (const [nom, aliases] of Object.entries(LEGACY_SLUGS)) {
    const { rows } = await client.query('SELECT id FROM activites WHERE nom_activite = $1', [nom]);
    if (!rows[0]) continue;
    for (const alias of aliases) {
      await client.query(
        'INSERT INTO activite_aliases (alias, activite_id) VALUES ($1,$2) ON CONFLICT (alias) DO NOTHING',
        [alias, rows[0].id]
      );
    }
  }
}

// The original project kept the activity as free text in adherents.activite.
// This moves those rows onto a real foreign key, resolving slugs through the
// alias table so historical values like "natation" still land on Swimming.
async function migrateLegacyAdherents(client) {
  const cols = await columnsOf(client, 'adherents');
  const isLegacy = cols.includes('activite') && !cols.includes('activite_id');
  if (!isLegacy) {
    await client.query(CREATE_ADHERENTS);
    return;
  }

  const hasStatus = cols.includes('statut');
  const hasCreated = cols.includes('created_at');
  const legacySlug = "lower(replace(replace(trim(l.activite), ' ', '-'), '_', '-'))";

  await client.query('ALTER TABLE adherents RENAME TO adherents_legacy');
  await client.query(CREATE_ADHERENTS);
  await client.query(`
    INSERT INTO adherents
      (id, prenom, nom, email, telephone, date_naissance, adresse, activite_id, statut, created_at)
    SELECT
      l.id, l.prenom, l.nom, l.email, l.telephone, l.date_naissance, l.adresse,
      COALESCE(
        (SELECT a2.id FROM activites a2 WHERE a2.slug = ${legacySlug}),
        (SELECT al.activite_id FROM activite_aliases al WHERE al.alias = ${legacySlug})
      ),
      ${hasStatus ? "COALESCE(l.statut, 'en_attente')" : `'en_attente'`},
      ${hasCreated ? 'COALESCE(l.created_at, now())' : 'now()'}
    FROM adherents_legacy l
    ORDER BY l.id;
  `);
  await client.query('DROP TABLE adherents_legacy');
  await client.query("SELECT setval(pg_get_serial_sequence('adherents','id'), COALESCE((SELECT max(id) FROM adherents), 1))");
}

let initPromise = null;

function init() {
  if (!initPromise) initPromise = runMigrations().catch((e) => {
    initPromise = null;
    throw e;
  });
  return initPromise;
}

async function runMigrations() {
  if (!connectionString) {
    throw new Error('DATABASE_URL is not set. Copy .env.example to .env or export the variable.');
  }

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    await client.query('CREATE TABLE IF NOT EXISTS schema_migrations (version integer PRIMARY KEY)');
    const { rows } = await client.query('SELECT version FROM schema_migrations');
    const current = rows.length ? rows[0].version : 0;
    if (current >= SCHEMA_VERSION) {
      await client.query('COMMIT');
      return;
    }

    await client.query(CREATE_ACTIVITES);
    // Serialises concurrent cold starts so two invocations cannot both seed.
    await client.query('LOCK TABLE activites IN ACCESS EXCLUSIVE MODE');
    await client.query(CREATE_ALIASES);
    await seedActivities(client);
    await seedAliases(client);
    await migrateLegacyAdherents(client);
    await client.query(CREATE_INDEXES);
    await client.query('INSERT INTO schema_migrations (version) VALUES ($1) ON CONFLICT DO NOTHING', [
      SCHEMA_VERSION,
    ]);

    await client.query('COMMIT');
  } catch (e) {
    await client.query('ROLLBACK').catch(() => {});
    throw e;
  } finally {
    client.release();
  }
}

// Development and test utility: wipe all data and restore the seeded
// activities. Never call this from a request handler.
async function resetDatabase() {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('TRUNCATE adherents, activite_aliases, activites RESTART IDENTITY CASCADE');
    await seedActivities(client);
    await seedAliases(client);
    await client.query('COMMIT');
  } catch (e) {
    await client.query('ROLLBACK').catch(() => {});
    throw e;
  } finally {
    client.release();
  }
}

const rows = async (text, params) => (await pool.query(text, params)).rows;
const one = async (text, params) => (await pool.query(text, params)).rows[0] || null;
const run = async (text, params) => (await pool.query(text, params)).rowCount;


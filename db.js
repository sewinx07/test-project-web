const { Pool } = require('pg');

const SCHEMA_VERSION = 1;

const CATEGORIES = ['ballon', 'eau', 'individuel', 'bien-etre'];
const DAYS = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
const STATUSES = ['actif', 'en_attente', 'suspendu'];

// pg does not understand Neon's channel_binding extension parameter.
const connectionString = (process.env.DATABASE_URL || '').replace(/[?&]channel_binding=[^&]*/i, '');

const pool = new Pool({
  connectionString,
  max: Number(process.env.PGPOOL_MAX) || 4,
  idleTimeoutMillis: 10_000,
  connectionTimeoutMillis: 10_000,
});

pool.on('error', (e) => console.error('[db] idle client error', e.message));

const inArray = (values) => values.map((v) => `'${String(v).replace(/'/g, "''")}'`).join(', ');

const toSlug = (value) =>
  String(value)
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 50);

